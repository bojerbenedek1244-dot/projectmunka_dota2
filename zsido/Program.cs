        static void FarmingPhase()
        {
            Console.WriteLine("\n--- MID LANE FARMOLÁS (Cél: 1000 Gold) ---");
            int enemyGold = gold;
            int wave = 1;

            while (gold < 1000)
            {
                int myCreeps = rnd.Next(1, 6);
                int enemyCreeps = rnd.Next(1, 6);

                int myEarned = myCreeps * 20;
                int enemyEarned = enemyCreeps * 20;

                gold += myEarned;
                enemyGold += enemyEarned;

                Console.WriteLine($"Hullám #{wave}: Elütöttél {myCreeps} creepet (+{myEarned}g) | Enemy: {enemyCreeps} creep (+{enemyEarned}g) -> Saját Gold: {gold}");
                wave++;
                Thread.Sleep(300);
            }

            Console.ForegroundColor = ConsoleColor.Yellow;
            Console.WriteLine($"\nElérted az 1000 Goldot! (Jelenlegi gold: {gold}, Enemy gold: {enemyGold})");
            Console.ResetColor();
        }

