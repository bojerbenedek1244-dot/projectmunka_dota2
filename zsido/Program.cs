                {
                    Console.ForegroundColor = ConsoleColor.Green;
                    Console.WriteLine("\n[SIKER]: A frontális roham áttörte a védelmet! Elestek a laktanyák.");
                    winScore += 2;
                    Console.ResetColor();
                }
                else
                {
                    Console.ForegroundColor = ConsoleColor.Red;
                    Console.WriteLine("\n[CSAPDA]: Rosszkor mentetek be, az enemy hősök letöröltek a torony alól!");
                    winScore = Math.Max(0, winScore - 1);
                    Console.ResetColor();
                }
            }
            else
            {
                if (roll <= 70)
                {
                    Console.ForegroundColor = ConsoleColor.Green;
                    Console.WriteLine("\n[MEGLEPETÉS]: A füstös akció sikeres volt! Sikerült leszedni a fő supportot.");
                    winScore += 2;
                    Console.ResetColor();
                }
                else
                {
                    Console.WriteLine("\n[IDŐVESZTESÉG]: Óvatoskodtunk, az enemy kitakarította a mapot, de legalább nem halt meg senki.");
                }
            }
            WaitForKey();
        }

