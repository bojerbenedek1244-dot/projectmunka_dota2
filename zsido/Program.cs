        static void FinalFightPhase()
        {
            Console.ForegroundColor = ConsoleColor.Cyan;
            Console.WriteLine("\n==================================================");
            Console.WriteLine("        VÉGSŐ TEAMFIGHT AZ ENEMY ANCIENTNÉL!       ");
            Console.WriteLine("==================================================");
            Console.ResetColor();

            Thread.Sleep(1000);

            if (hasAegis)
            {
                Console.WriteLine("-> Az Aegis of the Immortal védi az életedet: ha leterítenének, újra felállsz!");
            }
            if (hasShard)
            {
                Console.WriteLine("-> Az Aghanim's Shard képességed extra pusztítást végez a harcmezőn!");
            }
            if (hasBlink)
            {
                Console.WriteLine("-> Blink Daggerrel azonnal ráugrottál az enemy hátvédre!");
            }
            else if (critChance > 0)
            {
                Console.WriteLine("-> A Daedalus kritikus ütéseiddel sorra szeded le az ellenfeleket!");
            }

            int finalWinChance = winScore * 9;
            if (finalWinChance > 96) finalWinChance = 96;
            if (finalWinChance < 20) finalWinChance = 20;

            Console.WriteLine($"\nAz eddigi meccs alakulása alapján a végső győzelmi esélyed: {finalWinChance}%");
            Thread.Sleep(1500);

            int roll = rnd.Next(1, 101);
            if (roll <= finalWinChance)
            {
                Console.ForegroundColor = ConsoleColor.Green;
                Console.WriteLine("\n**************************************************");
                Console.WriteLine($"   VICTORY! GRATULÁLOK {playerName.ToUpper()}!   ");
                Console.WriteLine("   Leomlott az enemy Ancient, megnyerted a meccset!");
                Console.WriteLine("**************************************************");
                Console.ResetColor();
            }
            else
            {
                Console.ForegroundColor = ConsoleColor.Red;
                Console.WriteLine("\n**************************************************");
                Console.WriteLine("   DEFEAT! Sajnos az enemy megfordította a harcot. ");
                Console.WriteLine("   GG WP, következőre meglesz!                    ");
                Console.WriteLine("**************************************************");
                Console.ResetColor();
            }
        }

